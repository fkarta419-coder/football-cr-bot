# Состояния
class QuizStates(StatesGroup):
    waiting_answer = State()

# Хранилище данных пользователей
user_data = {}

@dp.message_handler(commands=['start'])
async def start(message: types.Message):
    await message.reply(
        "🎮 Привет! Я бот-квиз по футболистам!\n\n"
        "Напиши 'Квиз' чтобы начать игру!\n"
        "За каждого угаданного игрока ты получаешь 3 кубка! 🏆"
    )

@dp.message_handler(lambda message: message.text.lower() == 'квиз')
async def start_quiz(message: types.Message):
    user_id = message.from_user.id
    
    # Выбираем случайный клуб и игрока
    club_name = random.choice(list(CLUBS.keys()))
    player = random.choice(CLUBS[club_name])
    
    # Сохраняем данные
    user_data[user_id] = {
        'club': club_name,
        'player': player,
        'start_time': datetime.now(),
        'cups': user_data.get(user_id, {}).get('cubs', 0)
    }
    
    await message.reply(
        f"🎯 Угадай игрока!\n\n"
        f"🏟 Клуб: {club_name}\n"
        f"📊 Рейтинг: {player['рейтинг']}\n"
        f"📍 Позиция: {player['позиция']}\n\n"
        f"⏳ У тебя 5 минут!"
    )
    
    # Запускаем таймер
    asyncio.create_task(check_timeout(message, user_id))

async def check_timeout(message: types.Message, user_id: int):
    await asyncio.sleep(300)  # 5 минут
    
    if user_id in user_data and user_data[user_id]['start_time']:
        player = user_data[user_id]['player']
        await message.reply(
            f"⏰ Время вышло!\n"
            f"Правильный ответ: {player['имя']}\n\n"
            f"Напиши 'Квиз' чтобы сыграть ещё раз!"
        )
        del user_data[user_id]

@dp.message_handler(state=QuizStates.waiting_answer)
async def check_answer(message: types.Message, state: FSMContext):
    user_id = message.from_user.id
    
    if user_id not in user_data:
        await message.reply("Напиши 'Квиз' чтобы начать игру!")
        await state.finish()
        return
    
    data = user_data[user_id]
    player = data['player']
    
    # Проверяем ответ
    if message.text.lower() == player['имя'].lower():
        data['cups'] += 3
        await message.reply(
            f"✅ Правильно! Это {player['имя']}!\n"
            f"🏆 +3 кубка! Всего кубков: {data['cups']}\n\n"
            f"Напиши 'Квиз' чтобы сыграть ещё раз!"
        )
        del user_data[user_id]
        await state.finish()
    else:
        elapsed = datetime.now() - data['start_time']
        remaining = timedelta(minutes=5) - elapsed
        minutes = int(remaining.total_seconds() // 60)
        seconds = int(remaining.total_seconds() % 60)
        
        await message.reply(
            f"❌ Неверно. Пробуй ещё!\n"
            f"⏳ Осталось времени: {minutes}:{seconds:02d}"
        )

@dp.message_handler()
async def handle_message(message: types.Message):
    if message.text.lower() == 'квиз':
        await start_quiz(message)
    else:
        user_id = message.from_user.id
        if user_id in user_data:
            await check_answer(message, None)
        else:
            await message.reply("Напиши 'Квиз' чтобы начать игру!")

if __name__ == '__main__':
    executor.start_polling(dp, skip_updates=True)
